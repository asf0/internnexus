"""Filesystem anchors for the pipeline package.

This is the single place that resolves a location from ``__file__``.  Every
other module imports from here, so moving a module between directories can
never silently change which file it reads or writes.

Two data directories exist and are deliberately kept distinct:

``PACKAGE_DATA_DIR``
    Read-only lookup data shipped inside the wheel (category mappings, the
    curated company list).  Always package-relative.

``runtime_data_dir()``
    Writable output the pipeline produces at runtime (rejection logs,
    unmapped-category reports).  Honours ``$DATA_DIR`` and is resolved on
    every call so tests and deployments can redirect it.
"""

from __future__ import annotations

import os
from pathlib import Path

__all__ = [
    "PACKAGE_ROOT",
    "REPO_ROOT",
    "WORKSPACE_ROOT",
    "PACKAGE_DATA_DIR",
    "OUTPUT_DIR",
    "CONFIG_PATH",
    "ENV_FILE",
    "company_roster_dir",
    "runtime_data_dir",
]

# The one and only depth assumption in the package: this file lives at
# ``pipeline/infra/paths.py``, so parents[1] is ``pipeline/``.
PACKAGE_ROOT = Path(__file__).resolve().parents[1]

#: Repository checkout containing ``pipeline/``, ``backend/``, ``frontend/``.
REPO_ROOT = PACKAGE_ROOT.parent

#: Directory *above* the repository; the base for filesystem log paths.
WORKSPACE_ROOT = REPO_ROOT.parent

#: Read-only lookup data bundled into the wheel.
PACKAGE_DATA_DIR = PACKAGE_ROOT / "data"

#: Writable scratch output (CSV exports, slug caches).
OUTPUT_DIR = PACKAGE_ROOT / "output"

#: Pipeline YAML configuration.
CONFIG_PATH = PACKAGE_ROOT / "pipeline.yaml"

#: Repository-root ``.env`` consumed by pydantic settings.
ENV_FILE = REPO_ROOT / ".env"


def company_roster_dir() -> Path:
    """Directory holding the curated ATS company roster.

    Honours ``$DISCOVERY_OUTPUT_DIR``, which deployments point at a persistent
    volume. The name is historical: the roster used to be generated by a
    company-discovery step, which has since been retired in favour of a
    hand-curated list. The environment variable and on-disk filename are kept
    as they are so existing deployments keep resolving the same file.
    """
    override = os.environ.get("DISCOVERY_OUTPUT_DIR")
    return Path(override) if override else PACKAGE_ROOT / "data" / "roster"


def runtime_data_dir() -> Path:
    """Writable data directory, honouring ``$DATA_DIR``.

    Defaults to a relative ``data`` path (resolved against the working
    directory) to match the container layout, where ``WORKDIR`` is ``/app``
    and ``/app/data`` is created for this purpose.
    """
    return Path(os.getenv("DATA_DIR", "data"))
